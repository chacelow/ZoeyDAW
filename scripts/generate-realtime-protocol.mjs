function metadataType(type) {
  if (type.endsWith("?")) return `Option<${metadataType(type.slice(0, -1))}>`
  if (type.endsWith("[]")) return `Vec<${metadataType(type.slice(0, -2))}>`
  const primitive = rustPrimitive[type]
  if (primitive) return primitive
  if (!definitions.has(type)) throw new Error(`Unknown metadata type ${type}`)
  return type
}
const schemaName = name => `${name[0].toLowerCase()}${name.slice(1)}Schema`
function zodType(type) {
  if (type.endsWith("?")) return `${zodType(type.slice(0, -1))}.nullable()`
  if (type.endsWith("[]")) return `z.array(${zodType(type.slice(0, -2))}).readonly()`
  switch (type) {
    case "string":
      return "z.string()"
    case "bool":
      return "z.boolean()"
    case "u16":
      return "z.number().int().min(0).max(65535)"
    case "u32":
      return "z.number().int().min(0).max(4294967295)"
    case "f64":
      return "z.number().finite()"
    case "positive-f64":
      return "z.number().finite().positive()"
    case "json-u64":
      return "jsonU64Schema"
    default:
      if (!definitions.has(type)) throw new Error(`Unknown metadata type ${type}`)
      return schemaName(type)
  }
}
const derives = "#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]\n"
function zodFields(fields) {
  return Object.entries(fields)
    .map(([name, type]) => `    ${name}: ${zodType(type)},\n`)
    .join("")
}
function rustFields(fields, indent = "    ") {
  return Object.entries(fields)
    .map(([name, type]) => {
      const nullable = type.endsWith("?")
        ? `${indent}#[serde(deserialize_with = "deserialize_required_nullable")]\n`
        : ""
      return `${nullable}${indent}pub ${snake(name)}: ${metadataType(type)},\n`
    })
    .join("")
}
function zodUnion(name, union, contextSchema) {
  const options = Object.entries(union.variants)
    .map(
      ([value, fields]) =>
        `  z.object({\n${contextSchema ? `    ...${contextSchema}.shape,\n` : ""}    ${union.tag}: z.literal(${JSON.stringify(value)}),\n${zodFields(fields)}  }).strict(),\n`
    )
    .join("")
  return `export const ${schemaName(name)} = z.discriminatedUnion(${JSON.stringify(union.tag)}, [\n${options}]);\nexport type ${name} = z.infer<typeof ${schemaName(name)}>;\n`
}
