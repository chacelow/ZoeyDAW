for (const [name, envelope] of Object.entries(metadata.envelopes)) {
  const context = metadata.structs[envelope.context]
  const union = metadata.unions[envelope.payload]
  if (!context || !union) throw new Error(`Invalid envelope ${name}`)
  if (
    Object.values(union.variants).some(fields =>
      Object.keys(fields).some(key => Object.hasOwn(context, key))
    ) ||
    Object.hasOwn(context, union.tag)
  )
    throw new Error(`Overlapping envelope ${name}`)
  ts += zodUnion(name, union, schemaName(envelope.context))
  // Flattened serde structs combined with deny_unknown_fields payloads reject envelope keys.
  // Generate a single internally tagged enum instead, keeping exact-field validation in both languages.
  rust += `${derives}#[serde(tag = ${JSON.stringify(union.tag)}, rename_all_fields = "camelCase", deny_unknown_fields)]\npub enum ${name} {\n`
  for (const [value, fields] of Object.entries(union.variants)) {
    rust += `    #[serde(rename = ${JSON.stringify(value)})]\n    ${variant(value)} {\n${rustFields({ ...context, ...fields }, "        ").replaceAll("pub ", "")}    },\n`
  }
  rust += "}\n"
}
