// Regenerates presets.data.ts (next to this file) from the Web theme sources:
// - Default: the `:root` / `.dark` blocks of apps/web/src/index.css (Web's Default clears overrides);
// - every other preset: packages/ui/src/theme/theme-presets.ts (tweakcn).
// Only WEB_COLOR_TOKENS are kept; values are copied verbatim (hex / oklch keep full source precision).
// Run from anywhere: node apps/gpuix/src/shared/theme/generate-presets.mjs [--check]
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { THEME_PRESETS } from "../../../../../packages/ui/src/theme/theme-presets.ts"
import { WEB_COLOR_TOKENS } from "./web-tokens.ts"

const cssPath = fileURLToPath(new URL("../../../../web/src/index.css", import.meta.url))
const output = fileURLToPath(new URL("presets.data.ts", import.meta.url))

function cssBlock(css, selector) {
  const start = css.indexOf(`\n${selector} {`)
  if (start === -1) throw new Error(`index.css: missing ${selector} block`)
  const body = css.slice(start, css.indexOf("\n}", start))
  return Object.fromEntries(
    [...body.matchAll(/^\s+--([a-z0-9-]+):\s*([^;]+);/gm)].map(match => [match[1], match[2]])
  )
}

function pick(styles, where) {
  return Object.fromEntries(
    Object.entries(WEB_COLOR_TOKENS).map(([field, token]) => {
      const value = styles[token]
      if (!value) throw new Error(`${where}: missing --${token}`)
      return [field, value]
    })
  )
}

const css = await readFile(cssPath, "utf8")
const root = cssBlock(css, ":root")
const presets = THEME_PRESETS.map(({ id, label, styles }) =>
  id === ""
    ? {
        id: "default",
        label,
        light: pick(root, "index.css :root"),
        dark: pick({ ...root, ...cssBlock(css, ".dark") }, "index.css .dark"),
      }
    : { id, label, light: pick(styles.light, `${id}.light`), dark: pick(styles.dark, `${id}.dark`) }
)

// Printed in the repo's prettier style (2-space, no semicolons) so `ultracite fix` leaves it unchanged.
const colors = values =>
  Object.entries(values)
    .map(([field, value]) => `      ${field}: ${JSON.stringify(value)},`)
    .join("\n")
const entries = presets
  .map(
    ({ id, label, light, dark }) => `  {
    id: ${JSON.stringify(id)},
    label: ${JSON.stringify(label)},
    light: {
${colors(light)}
    },
    dark: {
${colors(dark)}
    },
  },`
  )
  .join("\n")
const source = `// Generated by generate-presets.mjs from apps/web/src/index.css and
// packages/ui/src/theme/theme-presets.ts. Do not edit by hand.
import type { ThemeColors } from "./colors"

export const PRESET_DATA = [
${entries}
] as const satisfies readonly {
  id: string
  label: string
  light: ThemeColors
  dark: ThemeColors
}[]
`

if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8").catch(() => "")) !== source) {
    console.error(
      "presets.data.ts is stale: run node apps/gpuix/src/shared/theme/generate-presets.mjs"
    )
    process.exit(1)
  }
} else {
  await writeFile(output, source)
}
