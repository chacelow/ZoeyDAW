import { afterEach, beforeEach, expect, it } from "bun:test"
import { projectActions, useProjectState } from "@/project/adapters"
import { mount, notes, seed } from "../harness.test"
import type { Harness } from "../harness.test"

let view: Harness | undefined
beforeEach(() => seed())
afterEach(() => {
  view?.unmount()
  view = undefined
})

it("returns pointer-selected piano-row focus to the grid for Delete and undo", () => {
  view = mount()
  const key = view.bounds("midi-key-64")
  const grid = view.root.renderer.findByTestId("midi-grid")
  if (!grid) throw new Error("Missing grid")
  view.root.renderer.nativeSimulateMouseDown(key.x + 4, key.y + key.height / 2)
  expect(useProjectState.getState().session.activeMidiNotes).toEqual([64])
  view.root.renderer.nativeSimulateMouseUp(key.x + 4, key.y + key.height / 2)
  expect(view.root.renderer.getFocusedElementId()).toBe(grid.id)
  view.root.renderer.simulateKeystrokes("delete")
  expect(notes().map(note => note.id)).toEqual(["retained"])
  view.root.renderer.simulateKeystrokes("cmd-z")
  expect(notes().map(note => note.id)).toEqual(["retained", "visible"])
  expect(useProjectState.getState().session.activeMidiNotes).toEqual([])
})

it("keeps keyboard audition on its key and releases pointer audition outside the key", () => {
  view = mount()
  const keyElement = view.root.renderer.findByTestId("midi-key-64")
  if (!keyElement) throw new Error("Missing key")
  const name = view.root.renderer.getElement(keyElement.id)?.customProps?.["aria-label"]
  expect(typeof name).toBe("string")
  expect(name).not.toMatch(/\((on|off)\)/)
  view.root.renderer.nativeSimulateKeyDown(keyElement.id, "enter")
  expect(useProjectState.getState().session.activeMidiNotes).toEqual([64])
  expect(view.root.renderer.getElement(keyElement.id)?.customProps?.["aria-label"]).toBe(name)
  view.root.renderer.nativeSimulateKeyUp(keyElement.id, "enter")
  expect(view.root.renderer.getFocusedElementId()).toBe(keyElement.id)
  expect(useProjectState.getState().session.activeMidiNotes).toEqual([])
  expect(view.root.renderer.getElement(keyElement.id)?.customProps?.["aria-label"]).toBe(name)
  const key = view.bounds("midi-key-64")
  view.root.renderer.nativeSimulateMouseDown(key.x + 4, key.y + key.height / 2)
  view.root.renderer.nativeSimulateMouseMove(1000, key.y, 0)
  view.root.renderer.nativeSimulateMouseUp(1000, key.y)
  expect(useProjectState.getState().session.activeMidiNotes).toEqual([])
})

it("edits the focused velocity stem without changing an unselected note", () => {
  view = mount()
  view.key("midi-velocity-retained", "right")
  view.key("midi-velocity-visible", "up")
  expect(notes().map(note => note.velocity)).toEqual([90, 81])
  view.key("midi-velocity-visible", "down")
  expect(notes().map(note => note.velocity)).toEqual([90, 80])
  projectActions.undo()
  expect(notes().map(note => note.velocity)).toEqual([90, 81])
  projectActions.undo()
  expect(notes().map(note => note.velocity)).toEqual([90, 80])
})

it("adjusts the selected velocity group and leaves Space for playback", () => {
  view = mount()
  view.key("midi-grid", "cmd-a")
  view.key("midi-velocity-retained", "up")
  expect(notes().map(note => note.velocity)).toEqual([91, 91])
  view.key("midi-velocity-retained", "space")
  expect(notes().map(note => note.velocity)).toEqual([91, 91])
  expect(useProjectState.getState().session.playing).toBe(true)
  expect(view.windowKeys).toEqual(["space"])
  view.key("midi-velocity-retained", "cmd-z")
  expect(notes().map(note => note.velocity)).toEqual([90, 80])
})

it("uses one Tab entry and roves the active velocity through the selection owner", () => {
  const h = (view = mount())
  h.key("midi-velocity-value", "tab")
  const first = h.root.renderer.findByTestId("midi-velocity-retained")
  if (!first) throw new Error("Missing active velocity")
  expect(h.root.renderer.getFocusedElementId()).toBe(first.id)
  h.root.renderer.simulateKeystrokes("right")
  const second = h.root.renderer.findByTestId("midi-velocity-visible")
  if (!second) throw new Error("Missing roved velocity")
  expect(h.root.renderer.getFocusedElementId()).toBe(second.id)
  expect(h.root.renderer.getAutomationTree()).toContain("1 selected")
  const slider = Object.values(h.root.renderer.getA11yTree().nodes ?? {}).filter(
    node => node.aria?.role === "Slider"
  )
  expect(slider).toHaveLength(1)
  expect(slider[0]?.aria?.label).toContain("3–4")
  expect(slider[0]?.aria?.value).toBe("80")
  h.root.renderer.simulateKeystrokes("up")
  expect(notes().map(note => note.velocity)).toEqual([90, 81])
  h.root.renderer.simulateKeystrokes("cmd-z")
  expect(notes().map(note => note.velocity)).toEqual([90, 80])
  h.root.renderer.simulateKeystrokes("left")
  expect(h.root.renderer.findByTestId("midi-velocity-retained")?.id).toBe(second.id)
  h.root.renderer.simulateKeystrokes("tab")
  expect(h.root.renderer.getFocusedElementId()).not.toBe(second.id)
})

it("synchronizes the active slider after pointer selection without another selection state", () => {
  const h = (view = mount())
  const box = h.bounds("midi-note-visible")
  h.root.renderer.nativeSimulateClick(box.x + 2, box.y + box.height / 2)
  expect(h.root.renderer.findByTestId("midi-velocity-visible")).toBeDefined()
  expect(h.root.renderer.findByTestId("midi-velocity-retained")).toBeUndefined()
  h.key("midi-velocity-visible", "down")
  expect(notes().map(note => note.velocity)).toEqual([90, 79])
  h.key("midi-velocity-visible", "cmd-z")
  expect(notes().map(note => note.velocity)).toEqual([90, 80])
})

it("uses the clicked group member as current velocity without reordering selection", () => {
  const h = (view = mount())
  h.key("midi-grid", "cmd-a")
  const box = h.bounds("midi-note-visible")
  h.root.renderer.nativeSimulateClick(box.x + 2, box.y + box.height / 2)
  expect(h.root.renderer.findByTestId("midi-velocity-visible")).toBeDefined()
  expect(h.root.renderer.getAutomationTree()).toContain("2 selected")
  h.key("midi-grid", "cmd-c")
  const copied: unknown = JSON.parse(h.clipboard.text ?? "null")
  expect(copied).toMatchObject({ notes: [{ pitch: 72 }, { pitch: 64 }] })
  h.key("midi-velocity-visible", "up")
  expect(notes().map(note => note.velocity)).toEqual([81, 81])
  h.key("midi-velocity-visible", "cmd-z")
  expect(notes().map(note => note.velocity)).toEqual([90, 80])
})

