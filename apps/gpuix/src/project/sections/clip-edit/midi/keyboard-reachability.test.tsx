it("Shift add and remove synchronize current note and group Undo", () => {
  const h = (view = mount())
  const first = h.bounds("midi-note-retained")
  const second = h.bounds("midi-note-visible")
  h.root.renderer.nativeSimulateClick(first.x + 2, first.y + first.height / 2)
  h.root.renderer.nativeSimulateClick(second.x + 2, second.y + second.height / 2, 0, "shift")
  expect(h.root.renderer.findByTestId("midi-velocity-visible")).toBeDefined()
  expect(h.root.renderer.getAutomationTree()).toContain("2 selected")
  h.key("midi-velocity-visible", "up")
  expect(notes().map(note => note.velocity)).toEqual([81, 81])
  h.key("midi-velocity-visible", "cmd-z")
  expect(notes().map(note => note.velocity)).toEqual([90, 80])
  h.root.renderer.nativeSimulateClick(second.x + 2, second.y + second.height / 2, 0, "shift")
  expect(h.root.renderer.findByTestId("midi-velocity-retained")).toBeDefined()
  expect(h.root.renderer.getAutomationTree()).toContain("1 selected")
})
